-- ForeverPilot / Logic/Provenance.lua
--
-- ОТКУДА ЧТО ВЗЯТО И НАСКОЛЬКО ОНО СВЕЖЕЕ - В ОДНОМ МЕСТЕ.
--
-- Аддон сшит из пяти источников с совершенно разной надёжностью, и до сих пор
-- это было видно только по отдельным пометкам на отдельных карточках:
--
--   персонаж         клиент, прямо сейчас            всегда свежее
--   цены             Auctionator                      ровно то, что игрок
--                                                     отсканировал сам
--   бонусы предметов внешняя база (Polestar_ItemDB)   генерация, не клиент
--   места и торговцы свои записи + Polestar.Codex      часть проверена ногами
--   история цен      наша собственная, суточная        дней ровно столько,
--                                                     сколько аддон работает
--
-- Игрок не технический, и спрашивать его «а Auctionator у вас сканировал?» -
-- бессмысленно. Поэтому ответ собран целиком, одной таблицей, и его можно
-- посмотреть в любой момент, если возникло сомнение: что аддон знает точно,
-- что из вторых рук, и чего не знает вовсе.
--
-- Ничего нового здесь не считается: все числа уже посчитаны теми, кто их
-- добывает. Это сводка, а не ещё один источник.
local ADDON, ns = ...

local U = ns.Util
local Api = ns.Api
local CONF = ns.CONF

local P = {}
ns.Provenance = P

-- Каждая строка: что это, откуда, насколько свежо, можно ли верить, и что
-- делать, если нельзя. Последнее поле - самое важное для игрока: «данных нет»
-- без «вот что с этим сделать» это просто жалоба.
--   { key, label, source, conf, fresh, detail, action }
function P:Rows()
    local rows = {}
    local function add(row) rows[#rows + 1] = row end

    -- 1. ПЕРСОНАЖ. Единственный источник, который не бывает устаревшим.
    local snap = ns.CharacterScanner and ns.CharacterScanner:Get() or nil
    add({
        key = "character",
        label = "Персонаж: уровень, класс, надетое, сумки, золото",
        source = "клиент игры, напрямую",
        conf = snap and (snap.equippedConf or CONF.EXACT) or CONF.UNKNOWN,
        fresh = "всегда свежее: читается на каждом пересчёте",
        detail = snap and (tostring(snap.level) .. " ур., "
            .. U.count(snap.bags) .. " "
            .. U.plural(U.count(snap.bags), "вид", "вида", "видов")
            .. " предметов в сумках, "
            .. U.money(snap.money or 0)) or "снимок ещё не сделан",
        action = (not snap) and "перезайдите в игру — снимок делается при входе" or nil,
    })

    -- 2. ЦЕНЫ. Главное ограничение всего аддона, и оно принципиальное.
    local ps = ns.PriceProvider and ns.PriceProvider:SourceSummary() or {}
    local fresh = ns.PriceProvider and ns.PriceProvider.Freshness
        and ns.PriceProvider:Freshness() or nil
    add({
        key = "prices",
        label = "Цены на аукционе",
        source = ps.auctionatorAvailable and "Auctionator" or "нет источника",
        conf = (not ps.auctionatorAvailable) and CONF.UNKNOWN
            or (fresh and fresh.stale and CONF.ESTIMATE or CONF.CACHED),
        -- БЕЗ AUCTIONATOR О СВЕЖЕСТИ ЦЕН ГОВОРИТЬ НЕЧЕГО. Раньше строка
        -- свежести бралась из памяти цен всегда, и на экране стояло «цены
        -- свежие: самой старой 1 час назад. Auctionator не загружен: всё
        -- денежное помечено как неизвестное» - два утверждения, из которых
        -- верным может быть только одно.
        fresh = (not ps.auctionatorAvailable) and "Auctionator не загружен — цен с аукциона нет"
            or (fresh and fresh.text or "цены ещё не спрашивались"),
        detail = ps.auctionatorAvailable
            and ("Auctionator знает ровно то, что вы отсканировали сами —"
                 .. " это не обойти"
                 -- «0 из 0» - не число, а «считать было нечего»: так и сказано.
                 .. (((tonumber(ps.total) or 0) > 0)
                     and (". Ответов за пересчёт: " .. tostring(ps.auctionator or 0)
                          .. " из " .. tostring(ps.total))
                     or ". За этот пересчёт цены не спрашивались"))
            or "всё денежное помечено как неизвестное",
        action = (not ps.auctionatorAvailable)
            and "включите Auctionator"
            or ((fresh and fresh.stale) and "зайдите на аукцион — пересчитаю сам" or nil),
    })

    -- 3. БОНУСЫ ПРЕДМЕТОВ. Клиент на этом сервере отдаёт только базовые
    -- характеристики; школьный урон, без которого сравнение вещей бессмысленно,
    -- есть только во внешней базе.
    local state = Api.ItemDBState and Api:ItemDBState() or "absent"
    local rows_ = Api.ItemDBCount and Api:ItemDBCount() or nil
    -- Сколько предметов за последний пересчёт остались без бонусов ВООБЩЕ:
    -- считает их сам сравниватель вещей (Gear:NoteUnreadable), по предметам, а
    -- не по чтениям.
    local unread = ns.GearAdvisor and ns.GearAdvisor.statsIncomplete or 0
    add({
        key = "itemStats",
        label = "Бонусы экипировки: сила магии, школьный урон, лечение",
        source = "внешняя база Polestar_ItemDB",
        conf = (state == "ready") and CONF.CACHED or CONF.UNKNOWN,
        fresh = (state == "ready") and "база в памяти"
            or (state == "loading" and "база ещё загружается — следующий пересчёт увидит"
                or "базы нет"),
        -- ТЕКСТ НЕ ПРО МАГА, И ПРИМЕР НЕ ИЗ ТРЁХ ШКОЛ МАГА.
        --
        -- Здесь было «без него сравнение вещей для мага неверно» и перечисление
        -- «тайный, огненный, ледяной» - то есть ровно три школы мага. Раздел
        -- «происхождение данных» читает любой класс: чернокнижник узнавал, что
        -- внешняя база нужна магу, и что школы бывают три. Школы берутся из
        -- ns.SPELL_SCHOOLS (их шесть, и это единственное место, где они
        -- перечислены), а «для мага» заменено на «вашего персонажа».
        -- ЗАВИСИМОСТЬ НАЗВАНА ВСЛУХ, А НЕ ВЫВЕДЕНА ИЗ ПОЛУТОНОВ.
        --
        -- Прежний текст объяснял, чего не хватает клиенту, но не говорил
        -- главного: без этой базы сравнение вещей НЕ РАБОТАЕТ - не «работает
        -- хуже». Из клиента приходят только базовые характеристики (в живом
        -- файле: 786 ответов C_Item.GetItemStats, и ни одного школьного урона),
        -- а решает сравнение именно школьный урон. Зависимость полная, и пока
        -- она не названа - она невидимая: игрок, у которого базы нет, получит
        -- те же уверенные карточки, посчитанные по половине характеристик.
        detail = "клиент на этом сервере отдаёт только базовые характеристики"
            .. " (выносливость, интеллект, броня). Школьный урон — и тайный, и"
            .. " теневой, и остальные — есть только здесь, а без него сравнение"
            .. " вещей неверно для любого, кто колдует"
            .. (rows_ and (". Строк в базе: " .. rows_) or "")
            .. ". Это полная зависимость: без Polestar_ItemDB сравнение вещей"
            .. " не работает вовсе — школьный урон прочитать больше негде"
            .. (((tonumber(unread) or 0) > 0)
                and (". Сейчас таких предметов " .. unread
                     .. ": их бонусы не прочитал никто — ни клиент, ни база")
                or ""),
        action = (state == "absent")
            and "поставьте Polestar_ItemDB, иначе вещи сравниваются неточно" or nil,
    })

    -- 4. МЕСТА. Половина своя (ходили ногами), половина чужая.
    local places = ns.Places and ns.Places:Summary() or {}
    add({
        key = "places",
        label = "Где стоят торговцы и тренеры",
        source = Api.CodexPresent and Api:CodexPresent()
            and "свои записи + Polestar.Codex" or "только свои записи",
        conf = ((places.routable or 0) > 0) and CONF.CACHED or CONF.UNKNOWN,
        -- СВЕЖЕСТЬ ТОГО, ЧЕГО НЕТ, - НЕ ОТВЕТ.
        --
        -- Здесь всегда стояло «свои записи не устаревают: NPC стоят на месте», и
        -- при нуле записей строка читалась так: «Свои записи не устаревают: NPC
        -- стоят на месте. Записанных мест пока нет.» Первая фраза - утверждение
        -- о сроке годности пустоты, и игроку она не отвечает ни на что. Когда
        -- записей нет, в графе свежести так и сказано; когда есть - там же
        -- стоит их число, которое раньше пряталось в пояснении.
        fresh = (((tonumber(places.npcs) or 0) > 0)
            and ("свои записи не устаревают: NPC стоят на месте, с координатами "
                 .. tostring(places.routable or 0) .. " из " .. tostring(places.npcs))
            or "записанных мест пока нет"),
        detail = "свои — те, перед кем вы стояли сами, им можно верить;"
            .. " из Codex — чужие данные, помечены как оценка",
        action = ((places.routable or 0) == 0)
            and "зайдите к любому торговцу — я запишу, где он стоит" or nil,
    })

    -- 5. ИСТОРИЯ ЦЕН. Наша собственная, и её ровно столько, сколько аддон
    -- работает. Это единственный источник, который нельзя добыть задним числом.
    local cov = ns.MarketHistory and ns.MarketHistory:Coverage() or {}
    add({
        key = "priceHistory",
        label = "История цен (моя собственная)",
        source = "суточные слепки, пишу сам с первого входа",
        conf = cov.short and CONF.ESTIMATE or CONF.CACHED,
        fresh = ((tonumber(cov.deepestDays) or 0) == 0) and "наблюдений ещё нет"
            or ((cov.deepestDays or 0) .. " "
                .. U.plural(cov.deepestDays or 0, "день", "дня", "дней") .. " наблюдений"
                .. (cov.short and " — выборка короткая" or "")),
        -- «НАБЛЮДЕНИЙ ЕЩЁ НЕТ. СУТОЧНЫХ СЛЕПКОВ ЦЕН ЕЩЁ НЕТ» - ОДНО И ТО ЖЕ
        -- ДВАЖДЫ В ОДНОЙ СТРОКЕ.
        --
        -- Первую фразу даёт графа свежести выше, вторую - MarketHistory:Coverage
        -- своим текстом для пустой истории. На экране они стояли рядом, и
        -- вторая не добавляла ничего. Поэтому при пустой истории берётся только
        -- то, чего в графе свежести нет: когда появится первая запись.
        detail = (((tonumber(cov.items) or 0) == 0)
                and "первый слепок появится после входа в игру"
                or (cov.text or "слепков ещё нет"))
            .. ". Задним числом её не собрать: сервер открылся 4 ноября, и"
            .. " сколько дней аддон работает — столько истории и есть",
        action = nil,
    })

    -- 6. СВОЯ КНИГА ЗАКУПОК. Единственный источник, который говорит не «просят
    -- столько», а «вы ОТДАЛИ столько». Пустая книга - это не сломанный
    -- источник: она заполняется сама, пока игрок играет, и ему для этого
    -- ничего делать не надо.
    local led = ns.Ledger and ns.Ledger:Report() or nil
    if led then
        add({
            key = "ledger",
            label = "Своя книга закупок: что вы заплатили и когда",
            source = "события игры: деньги и сумки, сверенные у торговца и у аукциона",
            conf = (led.entries > 0) and CONF.EXACT or CONF.ESTIMATE,
            fresh = (led.entries == 0)
                and "книга пока пуста — я заполняю её, пока вы играете"
                or (ns.Ledger:Headline()),
            detail = "здесь не то, сколько за предмет просят, а то, сколько вы"
                .. " за него отдали: себестоимость по этой книге — факт, а не"
                .. " оценка. Неоднозначную перемену я не записываю вовсе —"
                .. " лучше пустая строка, чем выдуманная цена"
                .. ((led.skipped or 0) > 0
                    and (". Отказов сверки: " .. led.skipped) or ""),
            action = nil,
        })
    end

    -- 7. ЧУЖАЯ КНИГА ЗАКУПОК. Строка есть только когда она действительно в
    -- игре. Названа чужой, и тут же сказано, что с ней будет дальше.
    if Api.MastercraftDB and Api:MastercraftDB() then
        add({
            key = "foreignBook",
            label = "Чужая книга закупок (запасной источник)",
            source = ns.FOREIGN_BOOK.name,
            conf = CONF.ESTIMATE,
            fresh = "обновляется без нас — когда именно, мы не знаем",
            detail = ns.FOREIGN_BOOK.why .. ". " .. U.capitalize(ns.FOREIGN_BOOK.plan),
            action = nil,
        })
    end

    -- 8. СОБСТВЕННЫЙ СПРАВОЧНИК - И СВЕРЕН ЛИ ОН С ИГРОЙ.
    --
    -- ПОЧЕМУ ЭТА СТРОКА ПОЯВИЛАСЬ. Сверка справочника с клиентом
    -- (Logic/SourceCheck.lua) у этого персонажа не состоялась ни разу: в
    -- справочнике нет рецептов ни по алхимии, ни по инженерному делу, ни по
    -- кулинарии, и сверять оказалось не с чем. Ветка при этом молчала, а
    -- результат лежал только в файле диагностики - то есть со стороны игрока
    -- «сверка не состоялась» было неотличимо от «всё сошлось». Разница
    -- существенная: во втором случае данным справочника можно верить, потому
    -- что их проверили, а в первом - нельзя, потому что их не проверял никто.
    --
    -- Строка ничего не считает: SourceCheck:Verdict читает уже сохранённый
    -- отчёт.
    local sc = ns.SourceCheck and ns.SourceCheck.Verdict and ns.SourceCheck:Verdict() or nil
    if sc then
        local FS = ns.ForeverSource
        local covers = (#(sc.reference or {}) > 0)
            and table.concat(sc.reference, ", ") or "ничего"
        local detail
        if not sc.ran then
            detail = "сверка ещё не запускалась — она идёт на первом пересчёте"
                .. " после входа в игру"
        elseif sc.compared > 0 then
            detail = "сверено рецептов: " .. sc.compared .. ", совпало "
                .. sc.matched .. ", расходится " .. sc.mismatched
                .. ". Расхождения я не исправляю молча — они лежат в отчёте"
        else
            -- Та самая честная формулировка: сверять не с чем, и справочник
            -- под эти профессии не пополняется. Причина - из самой сверки, а не
            -- переписанная здесь второй раз.
            detail = "сверки не было: " .. tostring(sc.reason or "причина не записана")
        end
        add({
            key = "sourceCheck",
            label = "Мой справочник: рецепты, торговцы, места",
            source = "собрано снаружи игры"
                .. ((FS and FS.BUILT) and (", " .. FS.BUILT) or ""),
            -- Непроверенные данные - это оценка, а не факт. «Неизвестно» здесь
            -- было бы неправдой: справочник есть и работает, непроверено
            -- именно согласие с игрой.
            conf = (sc.compared > 0) and CONF.CACHED or CONF.ESTIMATE,
            fresh = (sc.compared > 0)
                and "сверено с вашим клиентом на этом входе"
                or "с вашей игрой не сверено",
            detail = detail .. ". Справочник покрывает " .. covers,
            -- Делать игроку тут нечего, и предлагать ему что-то «сделать» было
            -- бы перекладыванием нашей работы: пополнять справочник - не его
            -- дело. Поэтому действия нет.
            action = nil,
        })
    end

    -- 9. ЛАГЕРЬ У КОСТРА. Строка есть только когда данные загружены.
    --
    -- Почему лагерь попал в этот список отдельной строкой: у него РАЗНАЯ
    -- надёжность внутри одного набора данных, и игрок имеет право это видеть.
    -- Номера предметов, реагенты и чертежи сошлись у двух независимых баз с
    -- диска - это проверяемо. Пороги навыка у двух объектов РАСХОДЯТСЯ, и
    -- Blizzard их уже правила хотфиксом. А описание бонуса есть только в одной
    -- базе, и вид бонуса из него выводили мы - значит это оценка, а не факт.
    --
    -- И самое важное: про сам лагерь игра не говорит НИЧЕГО. Что уже
    -- поставлено, идёт ли откат, сколько места осталось - этого нет ни в одной
    -- функции клиента, и никакие данные с диска этого не заменят.
    local campData = ns.CampData
    if campData and campData.OBJECTS then
        local disputed = 0
        for _, row in ipairs(campData.OBJECTS) do
            local a, b = tonumber(row.skill), tonumber(row.skillWT)
            if a and b and a ~= b then disputed = disputed + 1 end
        end
        add({
            key = "camp",
            label = "Лагерь у костра: предметы, пороги навыка и что они дают",
            source = "две базы с вашего диска, сверенные между собой",
            -- Не выше оценки: вид бонуса выведен нами из описания, а описание
            -- есть только в одной базе.
            conf = U.worstConf(campData.CONFIDENCE.SKILLS,
                               campData.CONFIDENCE.EFFECTS),
            fresh = "лежат на диске рядом с игрой — свежее ровно настолько,"
                .. " насколько вы их обновляли",
            detail = "предметов " .. #campData.OBJECTS .. ", профессий "
                .. #campData.PROFESSIONS .. ". Номера, реагенты и чертежи"
                .. " совпали у обоих источников"
                .. ((disputed > 0)
                    and (", а пороги навыка расходятся у " .. disputed .. " "
                         .. U.plural(disputed, "предмета", "предметов", "предметов")
                         .. " — там я беру бо́льшее число и говорю об этом на"
                         .. " карточке")
                    or "")
                .. ". Что уже поставлено в лагере и идёт ли откат, игра мне не"
                .. " сообщает: функций про лагерь в клиенте нет ни одной,"
                .. " поэтому советую по профессиям, сумкам и ценам",
            action = nil,
        })
    end

    -- 10. ПРЕДСКАЗАНИЕ. Отдельная строка, потому что это НЕ данные о настоящем.
    local ahead = ns.Foresight and ns.Foresight.result or nil
    if ahead then
        add({
            key = "foresight",
            label = "Что понадобится дальше (на вырост)",
            source = "невыученные рецепты из книги + внешние базы",
            conf = CONF.ESTIMATE,
            fresh = "пересобирается при росте уровня и подъёме потолка навыка",
            detail = "это предсказание, а не факт: " .. tostring(ahead.reagents.total)
                .. " материалов впереди уже копят историю цен, но советов по ним"
                .. " не выдаётся, пока они не станут применимы",
            action = nil,
        })
    end

    return rows
end

-- СТРОКА ИСТОЧНИКА - ЦЕЛЫМИ ФРАЗАМИ.
--
-- Экран склеивал куски сам: fresh .. ". " .. detail .. "  -> " .. action. Куски
-- при этом начинаются с маленькой буквы, а некоторые уже кончаются точкой, и
-- на экране стояло «…самой старой 1 час назад.. Auctionator знает…», «база в
-- памяти. клиент на этом сервере…». Склейка живёт здесь, одна: каждый кусок
-- становится фразой - с заглавной буквы и с одной точкой.
function P:RowText(row)
    local out = {}
    local function sentence(text, prefix)
        if type(text) ~= "string" then return end
        text = text:gsub("^%s+", ""):gsub("[%.%s]+$", "")
        if text == "" then return end
        out[#out + 1] = (prefix or "") .. ((prefix and text) or U.capitalize(text)) .. "."
    end
    sentence(row.fresh)
    sentence(row.detail)
    sentence(row.action, "Что сделать: ")
    return table.concat(out, " ")
end

-- Одна строка-итог для окна и для чата: чему можно верить, чему нет.
function P:Headline()
    local weak = {}
    for _, row in ipairs(P:Rows()) do
        if row.conf == CONF.UNKNOWN then weak[#weak + 1] = row.label end
    end
    if #weak == 0 then
        return "Все источники на месте. Про персонажа знаю точно, цены — из"
            .. " Auctionator с возрастом, бонусы вещей — из внешней базы."
    end
    return "Не хватает: " .. table.concat(weak, "; ")
        .. ". Остальное считаю как обычно, а это помечаю как неизвестное."
end

-- В диагностику, тем же составом: читающему файл не надо повторять расчёт.
function P:Report()
    if not ns.Diag then return nil end
    local rows = P:Rows()
    ns.Diag:Init().provenance = rows
    local unknown = 0
    for _, r in ipairs(rows) do
        if r.conf == CONF.UNKNOWN then unknown = unknown + 1 end
    end
    ns.Diag:Module("provenance", {
        ["in"] = #rows, out = #rows - unknown,
        unknown = unknown,
        headline = P:Headline(),
        reason = (unknown == #rows) and "ни один источник не ответил" or nil,
        reasonCode = (unknown == #rows) and "NO_API" or nil,
    })
    return rows
end

return P
